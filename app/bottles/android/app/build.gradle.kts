import java.util.Properties

// Maps API Key 从 local.properties 读，**不进仓库**。
// local.properties 已在 android/.gitignore 里。
//
// 为什么不直接写进 AndroidManifest：那个文件是要提交的，Key 一旦入库就等于公开，
// 而 Maps 系列的 Key 泄露会被刷爆账单。这里用 manifestPlaceholders 在构建期注入。
//
// 没配也能构建——地图会渲染成空白灰块并在日志里报 API key 错误，
// 但 App 其余部分照常工作，不至于因为少一把 Key 就编译不过。
val mapsApiKey: String = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}.getProperty("MAPS_API_KEY") ?: ""

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

